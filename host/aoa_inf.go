package main

import (
	"fmt"
	"strings"
	"time"
)

// aoaDeviceInterfaceGUID is the DeviceInterfaceGUIDs value registered by the
// WinUSB INFs; it must match packaging/windows/drawsplay-aoa.inf.
const aoaDeviceInterfaceGUID = "{8C7A2C7E-5B1F-4A6E-9D3B-5D2B7E0A1D42}"

// aoaWinUSBCatalogName is the catalog the Windows installer generates and
// signs for the INF from aoaWinUSBPackageInf.
const aoaWinUSBCatalogName = "drawsplay_winusb.cat"

// aoaComposite accessory PIDs whose accessory function is interface 0 of a
// composite device (accessory+ADB / accessory+audio[+ADB]).
var aoaCompositeAccessoryPIDs = map[uint16]bool{0x2d01: true, 0x2d04: true, 0x2d05: true}

// aoaWinUSBHardwareIDs lists the hardware IDs the WinUSB package binds: every
// AOA accessory identity (whole device, plus the accessory interface MI_00 of
// composite identities, for PCs where a vendor composite driver owns the
// parent) and the extra vid:pid pairs (tablets' normal-mode identities).
func aoaWinUSBHardwareIDs(extra [][2]uint16) []string {
	var ids []string
	seen := map[string]bool{}
	add := func(id string) {
		if !seen[id] {
			seen[id] = true
			ids = append(ids, id)
		}
	}
	for pid := aoaPIDFirst; pid <= aoaPIDLast; pid++ {
		add(fmt.Sprintf("USB\\VID_%04X&PID_%04X", aoaGoogleVID, pid))
		if aoaCompositeAccessoryPIDs[pid] {
			add(fmt.Sprintf("USB\\VID_%04X&PID_%04X&MI_00", aoaGoogleVID, pid))
		}
	}
	for _, id := range extra {
		add(fmt.Sprintf("USB\\VID_%04X&PID_%04X", id[0], id[1]))
	}
	return ids
}

// aoaWinUSBPackageInf returns an INF that binds the in-box WinUSB driver to
// hwids. It references aoaWinUSBCatalogName, which the installer generates
// and signs with a per-PC certificate so Windows accepts the package without
// Zadig. The header comment identifies DrawSplay-owned packages for removal.
func aoaWinUSBPackageInf(hwids []string, version time.Time) string {
	var models strings.Builder
	for _, id := range hwids {
		models.WriteString("%DeviceDesc% = USB_Install, " + id + "\r\n")
	}
	// DriverVer (each part <= 65535) increases with each install so a reinstall
	// outranks the previous package.
	v := version.UTC()
	driverVer := fmt.Sprintf("%s,1.%d.%d.%d", v.Format("01/02/2006"),
		v.Year()%100, v.YearDay(), (v.Hour()*3600+v.Minute()*60+v.Second())/2)
	inf := `; Generated by DrawSplay: binds WinUSB to Android accessory (AOA) and tablet USB identities.
[Version]
Signature   = "$Windows NT$"
Class       = USBDevice
ClassGuid   = {88BAE032-5A81-49f0-BC3D-A4FF138216D6}
Provider    = %ProviderName%
CatalogFile = ` + aoaWinUSBCatalogName + `
DriverVer   = ` + driverVer + `

[Manufacturer]
%ProviderName% = DrawSplayAOA,NTamd64,NTarm64

[DrawSplayAOA.NTamd64]
` + models.String() + `
[DrawSplayAOA.NTarm64]
` + models.String() + `
[USB_Install]
Include = winusb.inf
Needs   = WINUSB.NT

[USB_Install.Services]
Include = winusb.inf
Needs   = WINUSB.NT.Services

[USB_Install.HW]
AddReg = Dev_AddReg

[Dev_AddReg]
HKR,,DeviceInterfaceGUIDs,0x10000,"` + aoaDeviceInterfaceGUID + `"

[Strings]
ProviderName = "DrawSplay"
DeviceDesc   = "DrawSplay Tablet (USB)"
`
	return strings.ReplaceAll(strings.ReplaceAll(inf, "\r\n", "\n"), "\n", "\r\n")
}
