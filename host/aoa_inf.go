package main

import "fmt"

// aoaDeviceInterfaceGUID is the DeviceInterfaceGUIDs value registered by the
// WinUSB INFs; it must match packaging/windows/drawsplay-aoa.inf.
const aoaDeviceInterfaceGUID = "{8C7A2C7E-5B1F-4A6E-9D3B-5D2B7E0A1D42}"

// aoaWinUSBInf returns an INF that binds the in-box WinUSB driver to one USB
// VID/PID. The Windows host installs it on demand for the tablet's normal-mode
// identity, which differs per vendor and model and so cannot ship prebuilt.
func aoaWinUSBInf(vid, pid uint16) string {
	hwid := fmt.Sprintf("USB\\VID_%04X&PID_%04X", vid, pid)
	return `; Generated by DrawSplay: binds WinUSB to ` + hwid + `.
[Version]
Signature   = "$Windows NT$"
Class       = USBDevice
ClassGuid   = {88BAE032-5A81-49f0-BC3D-A4FF138216D6}
Provider    = %ProviderName%
DriverVer   = 10/15/2026,1.0.0.0

[Manufacturer]
%ProviderName% = DrawSplayAOA,NTamd64

[DrawSplayAOA.NTamd64]
%DeviceDesc% = USB_Install, ` + hwid + `

[USB_Install]
Include = winusb.inf
Needs   = WINUSB.NT

[USB_Install.Services]
Include = winusb.inf
Needs   = WINUSB.NT.Services

[USB_Install.HW]
AddReg = Dev_AddReg

[Dev_AddReg]
HKR,,DeviceInterfaceGUIDs,0x10000,"` + aoaDeviceInterfaceGUID + `"

[Strings]
ProviderName = "DrawSplay"
DeviceDesc   = "DrawSplay Tablet (USB)"
`
}
