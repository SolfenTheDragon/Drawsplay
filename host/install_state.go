package main

// Persisted install and driver-setup state, stored in the per-user config
// directory (%APPDATA%\DrawSplay on Windows) next to config.json.
//
//	install.json         — written by `-install`; its presence means the host
//	                       runs as an installed app and must never elevate on
//	                       its own at launch (one-time setup already ran).
//	winusb-attempts.json — WinUSB bindings already attempted per VID:PID, so a
//	                       failed or declined install never re-prompts on every
//	                       launch.
//	vdd-installed-by-drawsplay — marker: DrawSplay installed the virtual
//	                       display driver (uninstall may remove it without asking).

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
	"time"
)

const (
	installManifestName    = "install.json"
	winusbAttemptsName     = "winusb-attempts.json"
	installManifestVersion = 1
	// vddOwnedMarkerName records that DrawSplay (not the user) installed the
	// virtual display driver, so the uninstaller may remove it.
	vddOwnedMarkerName = "vdd-installed-by-drawsplay"
)

type winusbInfOwner int

const (
	winusbInfOther winusbInfOwner = iota
	winusbInfDrawSplay
	winusbInfZadigAOA
)

var aoaHardwareIDPattern = regexp.MustCompile(`(?i)usb\\vid_18d1&pid_2d0[0-5]`)

// isParsecVDDInf reports whether an installed INF is the Parsec Virtual
// Display Adapter driver package (hardware ID Root\Parsec\VDA). Parsec's USB
// drivers (virtual USB adapter, gamepads) are deliberately not matched.
func isParsecVDDInf(text string) bool {
	return strings.Contains(strings.ToLower(text), `root\parsec\vda`)
}

// classifyWinUSBInf identifies WinUSB driver packages the uninstaller may
// remove: ones DrawSplay generated (aoaWinUSBInf) and Zadig/libwdi packages
// for the AOA identities. Everything else (vendor drivers, other apps'
// accessory drivers) is winusbInfOther and left alone.
func classifyWinUSBInf(text string) winusbInfOwner {
	l := strings.ToLower(text)
	if !strings.Contains(l, "winusb") {
		return winusbInfOther
	}
	if strings.Contains(l, "; generated by drawsplay") {
		return winusbInfDrawSplay
	}
	if strings.Contains(l, "libwdi") && aoaHardwareIDPattern.MatchString(text) {
		return winusbInfZadigAOA
	}
	return winusbInfOther
}

// installManifest records what the one-time elevated install configured.
type installManifest struct {
	SchemaVersion   int               `json:"schemaVersion"`
	InstallDir      string            `json:"installDir"`
	HostExe         string            `json:"hostExe"`
	UninstallerExe  string            `json:"uninstallerExe"`
	InstalledAt     time.Time         `json:"installedAt"`
	VDDDriver       string            `json:"vddDriver,omitempty"`
	VDDOwned        bool              `json:"vddOwned,omitempty"`
	ParsecVDDOwned  bool              `json:"parsecVddOwned,omitempty"`
	WinUSBTask      string            `json:"winusbTask,omitempty"`
	DesktopShortcut string            `json:"desktopShortcut,omitempty"`
	WinUSB          map[string]string `json:"winusb,omitempty"`
	Warnings        []string          `json:"warnings,omitempty"`
}

type winusbAttempt struct {
	At     time.Time `json:"at"`
	Result string    `json:"result"`
}

type winusbAttemptState struct {
	Attempts map[string]winusbAttempt `json:"attempts"`
}

// userStateDir returns %APPDATA%\DrawSplay (os.UserConfigDir()/DrawSplay)
// without creating it.
func userStateDir() (string, error) {
	base, err := os.UserConfigDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(base, "DrawSplay"), nil
}

// writeJSONAtomic writes v as indented JSON via temp file + rename.
func writeJSONAtomic(path string, v any) error {
	data, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), filepath.Base(path)+".tmp-*")
	if err != nil {
		return err
	}
	_, err = tmp.Write(append(data, '\n'))
	closeErr := tmp.Close()
	if err == nil {
		err = closeErr
	}
	if err != nil {
		os.Remove(tmp.Name())
		return err
	}
	if err := os.Rename(tmp.Name(), path); err != nil {
		os.Remove(tmp.Name())
		return err
	}
	return nil
}

// readInstallManifest loads a manifest file. ok is false when the file does
// not exist; a corrupt file is an error.
func readInstallManifest(path string) (m installManifest, ok bool, err error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return installManifest{}, false, nil
	}
	if err != nil {
		return installManifest{}, false, err
	}
	if err := json.Unmarshal(data, &m); err != nil {
		return installManifest{}, false, fmt.Errorf("parse %s: %w", path, err)
	}
	return m, true, nil
}

// loadInstallManifest returns the current user's install manifest, if the
// host has been installed with `-install`.
func loadInstallManifest() (installManifest, bool) {
	dir, err := userStateDir()
	if err != nil {
		return installManifest{}, false
	}
	m, ok, err := readInstallManifest(filepath.Join(dir, installManifestName))
	if err != nil {
		fmt.Fprintf(os.Stderr, "Warning: ignoring install manifest: %v\n", err)
		return installManifest{}, false
	}
	return m, ok
}

func readWinUSBAttempts(path string) winusbAttemptState {
	st := winusbAttemptState{Attempts: map[string]winusbAttempt{}}
	data, err := os.ReadFile(path)
	if err != nil {
		return st
	}
	if json.Unmarshal(data, &st) != nil || st.Attempts == nil {
		return winusbAttemptState{Attempts: map[string]winusbAttempt{}}
	}
	return st
}

// winusbAttemptRecorded reports whether a WinUSB install for key ("vid:pid")
// was already attempted in an earlier run.
func winusbAttemptRecorded(dir, key string) bool {
	_, ok := readWinUSBAttempts(filepath.Join(dir, winusbAttemptsName)).Attempts[strings.ToLower(key)]
	return ok
}

func recordWinUSBAttempt(dir, key, result string, at time.Time) error {
	path := filepath.Join(dir, winusbAttemptsName)
	st := readWinUSBAttempts(path)
	st.Attempts[strings.ToLower(key)] = winusbAttempt{At: at.UTC(), Result: result}
	return writeJSONAtomic(path, st)
}

// isUninstallerExeName reports whether the executable was launched under an
// uninstaller name (DrawSplay-Uninstall.exe or its temp relaunch copy).
func isUninstallerExeName(path string) bool {
	return strings.Contains(strings.ToLower(filepath.Base(path)), "uninstall")
}

// isInstallerExeName reports whether path is the release installer (e.g.
// drawsplay_installer_v1.2.3.exe), which installs when launched without
// arguments instead of offering a portable run.
func isInstallerExeName(path string) bool {
	return strings.Contains(strings.ToLower(filepath.Base(path)), "installer") && !isUninstallerExeName(path)
}

// pathInsideDir reports whether path is dir or lies beneath it, comparing
// case-insensitively (Windows paths).
func pathInsideDir(path, dir string) bool {
	if path == "" || dir == "" {
		return false
	}
	p := strings.ToLower(filepath.Clean(path))
	d := strings.ToLower(filepath.Clean(dir))
	if p == d {
		return true
	}
	return strings.HasPrefix(p, strings.TrimRight(d, `\/`)+string(filepath.Separator))
}

// hiddenCommandContext is exec.CommandContext without a console window on
// Windows (the tray host has no console for children to inherit).
func hiddenCommandContext(ctx context.Context, name string, args ...string) *exec.Cmd {
	cmd := exec.CommandContext(ctx, name, args...)
	hideChildWindow(cmd)
	return cmd
}
